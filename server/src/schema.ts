import { index, integer, real, sqliteTable, text, uniqueIndex } from "drizzle-orm/sqlite-core";

export const analyses = sqliteTable("analyses", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  symbol: text("symbol").notNull().unique(),
  name: text("name").notNull(),
  market: text("market", { enum: ["US", "SGX"] }).notNull(),
  currency: text("currency"),
  entityType: text("entity_type", { enum: ["standard", "bank", "insurer", "reit"] }).notNull().default("standard"),
  asOfDate: text("as_of_date"),
  periodLabel: text("period_label").notNull().default("TTM"),
  shareBasis: text("share_basis", { enum: ["basic", "diluted"] }).notNull().default("diluted"),
  accountingBasis: text("accounting_basis", { enum: ["reported", "adjusted"] }).notNull().default("reported"),
  sourceLabel: text("source_label").notNull().default("Manual research input"),
  sourceUrl: text("source_url"),
  priceAtAnalysis: real("price_at_analysis"),
  priceCurrency: text("price_currency"),
  priceAsOf: text("price_as_of"),
  fcf: real("fcf"),
  growthRate: real("growth_rate"),
  terminalGrowth: real("terminal_growth"),
  discountRate: real("discount_rate"),
  cash: real("cash"),
  debt: real("debt"),
  shares: real("shares"),
  normalizedEps: real("normalized_eps"),
  fairPe: real("fair_pe"),
  revenue: real("revenue"),
  fairPs: real("fair_ps"),
  revenueGrowth: real("revenue_growth"),
  epsGrowth: real("eps_growth"),
  roic: real("roic"),
  debtEquity: real("debt_equity"),
  fcfMargin: real("fcf_margin"),
  interestCoverage: real("interest_coverage"),
  shareChange: real("share_change"),
  marginTrend: real("margin_trend"),
  dcfValue: real("dcf_value"),
  earningsValue: real("earnings_value"),
  salesValue: real("sales_value"),
  blendedValue: real("blended_value"),
  coveragePercent: real("coverage_percent").notNull().default(0),
  valuationStatus: text("valuation_status", { enum: ["ready", "blocked", "insufficient"] }).notNull().default("insufficient"),
  valuationMessage: text("valuation_message").notNull().default("Add tagged inputs before calculating."),
  sensitivityJson: text("sensitivity_json").notNull().default("[]"),
  qualityScore: real("quality_score"),
  qualityComplete: integer("quality_complete").notNull().default(0),
  analysisVersion: integer("analysis_version").notNull().default(1),
  notes: text("notes").notNull().default(""),
  createdAt: integer("created_at", { mode: "timestamp_ms" }).notNull().$defaultFn(() => new Date()),
  updatedAt: integer("updated_at", { mode: "timestamp_ms" }).notNull().$defaultFn(() => new Date()),
});

