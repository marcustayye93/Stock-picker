export const weeklyIdeaRuns = sqliteTable("weekly_idea_runs", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  weekKey: text("week_key").notNull(),
  asOfDate: text("as_of_date"),
  status: text("status", { enum: ["ready", "empty", "partial", "failed"] }).notNull().default("empty"),
  universeCount: integer("universe_count").notNull().default(0),
  quoteCount: integer("quote_count").notNull().default(0),
  eligibleCount: integer("eligible_count").notNull().default(0),
  matchCount: integer("match_count").notNull().default(0),
  errorCount: integer("error_count").notNull().default(0),
  earningsCheckedAt: integer("earnings_checked_at", { mode: "timestamp_ms" }),
  earningsCheckedThrough: text("earnings_checked_through"),
  earningsExcludedCount: integer("earnings_excluded_count").notNull().default(0),
  note: text("note"),
  scannedAt: integer("scanned_at", { mode: "timestamp_ms" }).notNull().$defaultFn(() => new Date()),
}, (table) => ({ weekKeyUnique: uniqueIndex("weekly_idea_runs_week_key_unique").on(table.weekKey) }));

export const weeklyIdeas = sqliteTable("weekly_ideas", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  runId: integer("run_id").notNull().references(() => weeklyIdeaRuns.id, { onDelete: "cascade" }),
  weekKey: text("week_key").notNull(),
  rank: integer("rank").notNull(),
  symbol: text("symbol").notNull(),
  name: text("name").notNull(),
  close: real("close").notNull(),
  asOfDate: text("as_of_date").notNull(),
  prior52WeekHigh: real("prior_52_week_high").notNull(),
  volumeMultiple: real("volume_multiple").notNull(),
  medianDollarVolume: real("median_dollar_volume").notNull(),
  realizedVolatility: real("realized_volatility").notNull(),
  setup: text("setup", { enum: ["breakout", "trend_pullback", "momentum_leader"] }).notNull().default("breakout"),
  setupJson: text("setup_json").notNull().default("{}"),
  historyJson: text("history_json"),
  benchmarkJson: text("benchmark_json"),
  sourceUrl: text("source_url"),
  createdAt: integer("created_at", { mode: "timestamp_ms" }).notNull().$defaultFn(() => new Date()),
}, (table) => ({
  weekSymbolUnique: uniqueIndex("weekly_ideas_week_symbol_unique").on(table.weekKey, table.symbol),
  runRankIdx: index("weekly_ideas_run_rank_idx").on(table.runId, table.rank),
}));
